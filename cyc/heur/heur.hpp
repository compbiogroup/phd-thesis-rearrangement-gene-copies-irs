/* Options of the heuristics that generate multiple decompositions. */
struct HeurArgs {
  bool all = false; // whether to output all decompositions or only the best one
  // Parameters for the genetic algorithm
  int tournament_size = 2;
  int mutation_rate = 50;
  int crossover_rate = 50;
};

const vector<option> heur_longopts = {{"mutation", 1, NULL, 'm'},
                                      {"crossover", 1, NULL, 'c'},
                                      {"tournament", 1, NULL, 't'},
                                      {"all", 0, NULL, 'a'}};

const string heur_str = "m:c:t:a";

void heur_help();
bool read_heur_args(HeurArgs &args, int op, char *optarg);

/* Generate decompositions of cg with heuristic heur (rand|ga) using the
 * decomposition algorithm dec_algo and return the best one. If all_os is not
 * null, every decomposition generated by the GA is written to it. */
unique_ptr<CycleGraph> best_decomposition(const CycleGraph &cg,
                                          const string &heur,
                                          const string &dec_algo,
                                          int iterations, const HeurArgs &args,
                                          ostream *all_os, Timer &timer,
                                          mt19937 &rand_gen);
